const STORAGE_KEY = "fod2_lang";

function formatCzPlural(n, one, few, many) {
  let resolvedOne = one;
  let resolvedFew = few;
  let resolvedMany = many;

  if (Array.isArray(one)) {
    [resolvedOne, resolvedFew, resolvedMany] = one;
  }

  const num = Number(n);
  const absNum = Number.isFinite(num) ? Math.abs(num) : 0;

  let form = resolvedMany;
  if (absNum === 1) {
    form = resolvedOne;
  } else if (Number.isInteger(absNum) && absNum >= 2 && absNum <= 4) {
    form = resolvedFew;
  }

  if (Array.isArray(one)) {
    return `${absNum} ${form}`;
  }
  return form;
}

function getFestivalLang() {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved === "cs" || saved === "en") return saved;
  } catch (e) {
    // Fallback if storage is unavailable
  }
  return "en";
}

function applyTranslations(lang) {
  const dict = FESTIVAL_I18N[lang] || FESTIVAL_I18N.en;
  document.documentElement.lang = lang;

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (key && Object.prototype.hasOwnProperty.call(dict, key)) {
      el.textContent = dict[key];
    }
  });

  document.querySelectorAll("[data-plural-count]").forEach((el) => {
    const count = Number(el.getAttribute("data-plural-count")) || 0;
    if (lang === "cs") {
      el.textContent = `${count} ${formatCzPlural(count, "set", "sety", "setů")}`;
    } else {
      el.textContent = count === 1 ? "1 set" : `${count} sets`;
    }
  });

  const toggleBtn = document.getElementById("lang-toggle");
  if (toggleBtn) {
    toggleBtn.textContent = lang === "en" ? "CZ" : "EN";
  }
}

function setFestivalLang(lang) {
  const normalized = lang === "cs" ? "cs" : "en";
  try {
    localStorage.setItem(STORAGE_KEY, normalized);
  } catch (e) {
    // Ignore storage errors
  }
  applyTranslations(normalized);
  return normalized;
}

function toggleFestivalLang() {
  const current = getFestivalLang();
  return setFestivalLang(current === "en" ? "cs" : "en");
}

